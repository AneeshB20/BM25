// Evaluates BM25 on the judged test queries of a BEIR dataset.
//
//   bm25_eval [--data DIR] [--out RUN] [--metrics-out TSV] [-k N]
//             [--k1 X] [--b X] [--no-stem] [--no-stopwords]
//       Runs every judged query, writes a TREC run (qid Q0 docid rank score tag),
//       per-query metrics, and prints mean nDCG@10 and Recall@100.
//
//   bm25_eval --ablations MD [--data DIR] [--runs-dir DIR]
//       Runs the tokenizer ablations and the k1 x b grid and writes a Markdown table.
//       With --runs-dir, also writes each configuration's run file there.

#include <chrono>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <exception>
#include <memory>
#include <stdexcept>
#include <string>
#include <vector>

#include "bm25/corpus.hpp"
#include "bm25/inverted_index.hpp"
#include "bm25/metrics.hpp"
#include "bm25/searcher.hpp"
#include "bm25/tokenizer.hpp"

namespace {

using Clock = std::chrono::steady_clock;

struct FileCloser {
    void operator()(std::FILE* f) const {
        if (f) std::fclose(f);
    }
};
using File = std::unique_ptr<std::FILE, FileCloser>;

File open_for_write(const std::string& path) {
    if (path.empty()) return File(nullptr);
    File f(std::fopen(path.c_str(), "w"));
    if (!f) throw std::runtime_error("cannot write " + path);
    return f;
}

struct EvalResult {
    double ndcg10 = 0.0;
    double recall100 = 0.0;
    std::size_t num_queries = 0;
    double query_ms = 0.0;  // total wall time spent in Searcher::search
};

// Runs all judged queries. Optionally writes the TREC run and per-query metrics.
EvalResult evaluate(const bm25::Corpus& corpus, const bm25::InvertedIndex& index,
                    const bm25::Tokenizer& tokenizer, const bm25::Bm25Params& params,
                    std::size_t depth, const std::string& tag, std::FILE* run_out,
                    std::FILE* metrics_out) {
    const bm25::Searcher searcher(index, tokenizer, params);
    EvalResult res;
    if (metrics_out) std::fprintf(metrics_out, "query_id\tndcg_cut_10\trecall_100\n");

    for (const bm25::Query& q : corpus.judged_queries()) {
        const auto t0 = Clock::now();
        const auto hits = searcher.search(q.text, depth);
        res.query_ms += std::chrono::duration<double, std::milli>(Clock::now() - t0).count();

        std::vector<std::string> ranked;
        ranked.reserve(hits.size());
        for (std::size_t r = 0; r < hits.size(); ++r) {
            const std::string& docid = index.external_id(hits[r].doc_id);
            ranked.push_back(docid);
            if (run_out) {
                std::fprintf(run_out, "%s Q0 %s %zu %.9f %s\n", q.id.c_str(), docid.c_str(), r + 1,
                             hits[r].score, tag.c_str());
            }
        }
        const auto& judged = corpus.qrels().at(q.id);
        const double ndcg = bm25::Metrics::ndcg_at_k(ranked, judged, 10);
        const double recall = bm25::Metrics::recall_at_k(ranked, judged, 100);
        if (metrics_out) std::fprintf(metrics_out, "%s\t%.6f\t%.6f\n", q.id.c_str(), ndcg, recall);
        res.ndcg10 += ndcg;
        res.recall100 += recall;
        ++res.num_queries;
    }
    if (res.num_queries > 0) {
        res.ndcg10 /= static_cast<double>(res.num_queries);
        res.recall100 /= static_cast<double>(res.num_queries);
    }
    if (metrics_out) {
        std::fprintf(metrics_out, "all\t%.6f\t%.6f\n", res.ndcg10, res.recall100);
    }
    return res;
}

const char* on_off(bool b) { return b ? "on" : "off"; }

int run_ablations(const bm25::Corpus& corpus, const std::string& md_path,
                  const std::string& runs_dir) {
    struct TokConfig {
        const char* name;
        bm25::TokenizerOptions opts;
    };
    const std::vector<TokConfig> tok_configs = {
        {"no stemming, no stopwords", {false, false}},
        {"stopwords only", {true, false}},
        {"stemming only", {false, true}},
        {"stemming + stopwords (main)", {true, true}},
    };
    const bm25::Bm25Params main_params{0.9, 0.4};
    const std::size_t depth = 100;

    File md = open_for_write(md_path);
    std::FILE* out = md.get();
    std::fprintf(out, "# Ablations on BEIR SciFact (test split, %zu queries)\n\n",
                 corpus.judged_queries().size());
    std::fprintf(out, "Generated by `build/apps/bm25_eval --ablations %s`.\n", md_path.c_str());
    std::fprintf(out, "Title and text are indexed as one field. Metrics are means over all judged\n"
                      "test queries; nDCG@10 uses linear gain, as trec_eval does.\n\n");

    auto run_name = [&](const TokConfig& tc, const bm25::Bm25Params& p) {
        char buf[128];
        std::snprintf(buf, sizeof buf, "%s/bm25_stem-%s_stop-%s_k1-%.2f_b-%.2f.trec", runs_dir.c_str(),
                      on_off(tc.opts.stem), on_off(tc.opts.remove_stopwords), p.k1, p.b);
        return std::string(buf);
    };

    // Table 1: tokenizer ablations at the main BM25 parameters.
    std::fprintf(out, "## Tokenizer ablations (k1 = 0.9, b = 0.4)\n\n");
    std::fprintf(out, "| Configuration | Stemming | Stopwords | Vocabulary | nDCG@10 | Recall@100 |\n");
    std::fprintf(out, "|---|---|---|---:|---:|---:|\n");
    for (const TokConfig& tc : tok_configs) {
        const bm25::Tokenizer tok(tc.opts);
        bm25::InvertedIndex index;
        index.build(corpus.documents(), tok);
        File run = open_for_write(runs_dir.empty() ? "" : run_name(tc, main_params));
        const EvalResult r = evaluate(corpus, index, tok, main_params, depth, "bm25", run.get(), nullptr);
        std::fprintf(out, "| %s | %s | %s | %zu | %.4f | %.4f |\n", tc.name, on_off(tc.opts.stem),
                     on_off(tc.opts.remove_stopwords), index.stats().vocab_size, r.ndcg10, r.recall100);
        std::printf("%-30s nDCG@10 %.4f  Recall@100 %.4f\n", tc.name, r.ndcg10, r.recall100);
    }

    // Table 2: k1 x b grid with the main tokenizer.
    std::fprintf(out, "\n## BM25 parameter grid (stemming + stopwords)\n\n");
    std::fprintf(out, "| k1 | b | nDCG@10 | Recall@100 |\n|---:|---:|---:|---:|\n");
    const TokConfig& main_tok = tok_configs.back();
    const bm25::Tokenizer tok(main_tok.opts);
    bm25::InvertedIndex index;
    index.build(corpus.documents(), tok);
    for (double k1 : {0.9, 1.2, 1.5}) {
        for (double b : {0.4, 0.75}) {
            const bm25::Bm25Params p{k1, b};
            File run = open_for_write(runs_dir.empty() ? "" : run_name(main_tok, p));
            const EvalResult r = evaluate(corpus, index, tok, p, depth, "bm25", run.get(), nullptr);
            const bool is_main = k1 == main_params.k1 && b == main_params.b;
            std::fprintf(out, "| %.1f | %.2f | %.4f%s | %.4f |\n", k1, b, r.ndcg10, is_main ? " (main)" : "",
                         r.recall100);
            std::printf("k1=%.1f b=%.2f                  nDCG@10 %.4f  Recall@100 %.4f\n", k1, b,
                        r.ndcg10, r.recall100);
        }
    }
    std::printf("wrote %s\n", md_path.c_str());
    return 0;
}

void usage() {
    std::fprintf(stderr,
                 "usage: bm25_eval [--data DIR] [--out RUN] [--metrics-out TSV] [-k N]\n"
                 "                 [--k1 X] [--b X] [--no-stem] [--no-stopwords] [--tag NAME]\n"
                 "       bm25_eval --ablations MD [--data DIR] [--runs-dir DIR]\n");
}

}  // namespace

int main(int argc, char** argv) {
    std::string data_dir = "data/scifact";
    std::string run_path = "results/bm25_run.trec";
    std::string metrics_path = "results/bm25_metrics.tsv";
    std::string ablations_path;
    std::string runs_dir;
    std::string tag = "bm25";
    std::size_t depth = 100;
    bm25::TokenizerOptions opts;
    bm25::Bm25Params params;

    for (int i = 1; i < argc; ++i) {
        const bool has_value = i + 1 < argc;
        if (std::strcmp(argv[i], "--data") == 0 && has_value) {
            data_dir = argv[++i];
        } else if (std::strcmp(argv[i], "--out") == 0 && has_value) {
            run_path = argv[++i];
        } else if (std::strcmp(argv[i], "--metrics-out") == 0 && has_value) {
            metrics_path = argv[++i];
        } else if (std::strcmp(argv[i], "--ablations") == 0 && has_value) {
            ablations_path = argv[++i];
        } else if (std::strcmp(argv[i], "--runs-dir") == 0 && has_value) {
            runs_dir = argv[++i];
        } else if (std::strcmp(argv[i], "--tag") == 0 && has_value) {
            tag = argv[++i];
        } else if (std::strcmp(argv[i], "-k") == 0 && has_value) {
            depth = std::strtoul(argv[++i], nullptr, 10);
        } else if (std::strcmp(argv[i], "--k1") == 0 && has_value) {
            params.k1 = std::strtod(argv[++i], nullptr);
        } else if (std::strcmp(argv[i], "--b") == 0 && has_value) {
            params.b = std::strtod(argv[++i], nullptr);
        } else if (std::strcmp(argv[i], "--no-stem") == 0) {
            opts.stem = false;
        } else if (std::strcmp(argv[i], "--no-stopwords") == 0) {
            opts.remove_stopwords = false;
        } else {
            usage();
            return 2;
        }
    }

    try {
        const bm25::Corpus corpus = bm25::Corpus::load(data_dir);
        if (!ablations_path.empty()) {
            return run_ablations(corpus, ablations_path, runs_dir);
        }

        const bm25::Tokenizer tokenizer(opts);
        bm25::InvertedIndex index;
        index.build(corpus.documents(), tokenizer);

        File run = open_for_write(run_path);
        File metrics = open_for_write(metrics_path);
        const EvalResult r =
            evaluate(corpus, index, tokenizer, params, depth, tag, run.get(), metrics.get());

        std::printf("config:      stem=%s stopwords=%s k1=%.2f b=%.2f depth=%zu\n", on_off(opts.stem),
                    on_off(opts.remove_stopwords), params.k1, params.b, depth);
        std::printf("queries:     %zu\n", r.num_queries);
        std::printf("nDCG@10:     %.4f\n", r.ndcg10);
        std::printf("Recall@100:  %.4f\n", r.recall100);
        std::printf("query time:  %.1f ms total, %.3f ms/query (single run, untuned)\n", r.query_ms,
                    r.num_queries ? r.query_ms / static_cast<double>(r.num_queries) : 0.0);
        if (!run_path.empty()) std::printf("run file:    %s\n", run_path.c_str());
        if (!metrics_path.empty()) std::printf("per-query:   %s\n", metrics_path.c_str());
    } catch (const std::exception& e) {
        std::fprintf(stderr, "error: %s\n", e.what());
        return 1;
    }
    return 0;
}
